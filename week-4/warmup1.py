numbers = [56, 8, 3, 89, 21, 4, 77, 54]
print(numbers[0])               # First: 56
print(numbers[-1])              # Last: 54
print(numbers[2:6])             # Middle: [3, 89, 21, 4]
                                
numbers.reverse()
print(numbers)                  # Reversed: [54, 77, 4, 21, 89, 3, 8, 56]           
